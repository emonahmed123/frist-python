import math

#square root of 16
print(math.sqrt(16))


# Power of 4 raised to 2
print(math.pow(4,2 ))

#Trigonometric functions

print(math.sin(math.radians(90))) # Sine of 90 degrees
print(math.cos(math.radians(0))) # Cosine of 0 degrees
print(math.tan(math.radians(45))) # Tangent of 45 degrees

# Logarithmic functions
print(math.log10(100)) # Log base 10 of 100


# Factorial of 5
print(math.factorial(5))

# absolute value of -10
print(math.fabs(-10))

# floor of 3.7
print(math.floor(3.7))
# ceiling of 3.2
print(math.ceil(3.2))

# constants
print(math.pi) # Value of pi
print(math.e)  # Value of e



#Greatest common divisor
print(math.gcd(48, 18)) # GCD of 48 and 18


print(math.lcm(12, 15)) # LCM of 12 and 15
