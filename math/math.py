import math

#square root of 16
print(math.sqrt(16))


# Power of 4 raised to 2
print(math.pow(4,2 ))

#Trigonometric functions

print(math.sin(math.radians(90))) # Sine of 90 degrees
print(math.cos(math.radians(0))) # Cosine of 0 degrees
print(math.tan(math.radians(45))) # Tangent of 45 degrees

# Logarithmic functions
print(math.log10(100)) # Log base 10 of 100


# Factorial of 5
print(math.factorial(5))